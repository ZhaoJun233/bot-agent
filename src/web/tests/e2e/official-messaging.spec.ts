import { expect, test } from '@playwright/test'

test('official messaging: real host read scope, no writes, fresh observations, keyboard and narrow screen', async ({ page }, testInfo) => {
  const writes: string[] = []
  page.on('request', request => {
    if (request.method() === 'POST' && /\/(execute|save|validate)$/.test(new URL(request.url()).pathname)) writes.push(request.url())
  })
  await page.goto('/')
  await page.getByTestId('token-input').fill('synthetic-web-read-token')
  await page.getByTestId('connect-button').click()
  await expect(page.getByTestId('overview')).toBeVisible()
  await page.getByTestId('nav-capabilities').click()
  const trigger = page.getByTestId('cap-messaging-driver:qq.official / legacy')
  await expect(trigger).toBeVisible()
  const firstResponse = page.waitForResponse(response => response.url().endsWith('/capabilities/inspect'))
  await trigger.click()
  const first = await (await firstResponse).json()
  await expect(page.getByTestId('messaging-list')).toBeVisible()
  expect(first.messaging.items).toHaveLength(13)
  expect(first.messaging.items.every((item: { applicationGrant: { state: number } }) => item.applicationGrant.state === 2)).toBe(true)
  await expect(page.getByTestId('messaging-text')).toContainText('暂不可用')
  await expect(page.getByTestId('messaging-markdown')).toContainText('待交付')
  await page.screenshot({ path: testInfo.outputPath('official-messaging-desktop.png'), animations: 'disabled' })
  await page.getByTestId('messaging-reason-recall').click()
  await expect(page.getByTestId('messaging-reason-dialog')).toContainText('两分钟内由机器人发送')
  await page.screenshot({ path: testInfo.outputPath('official-messaging-reason.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('messaging-reason-dialog')).toHaveCount(0)
  await expect(page.getByTestId('messaging-reason-recall')).toBeFocused()
  const nextResponse = page.waitForResponse(response => response.url().endsWith('/capabilities/inspect'))
  await page.getByTestId('messaging-refresh').click()
  const next = await (await nextResponse).json()
  expect(Date.parse(next.messaging.observedAt)).toBeGreaterThan(Date.parse(first.messaging.observedAt))
  expect(next.descriptor.descriptorRevision).toBe(first.descriptor.descriptorRevision)
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByTestId('official-messaging-dialog-close')).toBeInViewport()
  const dialog = page.getByTestId('official-messaging-dialog').getByRole('dialog')
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('official-messaging-mobile.png'), animations: 'disabled' })
  await page.getByTestId('official-messaging-dialog-close').click()
  await expect(page.getByTestId('official-messaging-dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(writes).toEqual([])
})
