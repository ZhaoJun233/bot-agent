using System.Collections.Concurrent;
using System.Security.Cryptography;
using System.Text;

namespace BotAgent.Plugins.WebUi;

/// <summary>
/// 面板会话与口令校验。
///
/// 为什么需要它：<c>AppSettings.PanelToken</c> 这个字段一直存在，但从来没有人校验过它 ——
/// 面板的 <c>/api/*</c> 是全开放的。任何能访问到端口的人都能读全部配置、改全部配置、
/// 拿诊断报告、代发消息。这不是"配置项没接上"，是"门根本不存在"。
///
/// 三条纪律：
///   ① 口令比对走**常量时间**：普通字符串比较会在第一个不同字节处提前返回，
///      攻击者能按响应耗时逐字节猜出正确口令；
///   ② 会话标识用**密码学随机数**，不用自增/时间戳，避免被预测；
///   ③ 登录失败按来源限流：面板暴露在内网时，暴力破解是真实威胁。
/// </summary>
public sealed class PanelSessionStore
{
    /// <summary>会话 Cookie 名。HttpOnly 由响应头保证，JS 读不到 —— XSS 也偷不走。</summary>
    public const string CookieName = "botagent_sid";

    /// <summary>会话有效期。到期即失效，每次访问滑动续期（长时间不用就得重新登录）。</summary>
    private static readonly TimeSpan SessionTtl = TimeSpan.FromHours(12);

    /// <summary>同一来源在窗口内允许的失败次数。超过则短暂拒绝，压住暴力破解。</summary>
    private const int MaxFailuresPerWindow = 5;

    private static readonly TimeSpan FailureWindow = TimeSpan.FromMinutes(5);

    private sealed class SessionEntry
    {
        public long ExpiresAtUnix;
    }

    private sealed class FailureEntry
    {
        public int Count;
        public long WindowStartUnix;
    }

    private readonly ConcurrentDictionary<string, SessionEntry> _sessions = new(StringComparer.Ordinal);
    private readonly ConcurrentDictionary<string, FailureEntry> _failures = new(StringComparer.Ordinal);
    private readonly byte[] _passwordBytes;
    private readonly Action<string> _log;

    /// <summary>当前生效的口令（供启动日志与密码文件写入用，不在任何 HTTP 响应里出现）。</summary>
    public string Password { get; }

    /// <summary>口令是否由系统自动生成（true = 用户没配环境变量，需要去读密码文件）。</summary>
    public bool PasswordAutoGenerated { get; }

    public PanelSessionStore(string? configuredToken, Action<string> log)
    {
        _log = log;

        var token = (configuredToken ?? string.Empty).Trim();
        if (token.Length == 0)
        {
            // 没配口令 ≠ 不设防。安全默认：生成一个随机口令并落到只有本用户可读的文件里，
            // 用户随时能找回；不这么做的话，"忘了配环境变量"就等于"面板裸奔"。
            token = GeneratePassword();
            PasswordAutoGenerated = true;
        }

        Password = token;
        _passwordBytes = Encoding.UTF8.GetBytes(token);
    }

    private static string GeneratePassword()
    {
        // 18 字节随机 → Base64Url 24 字符。够长到不可暴力猜，又能手抄。
        var raw = RandomNumberGenerator.GetBytes(18);
        return Convert.ToBase64String(raw)
            .Replace('+', '-')
            .Replace('/', '_')
            .TrimEnd('=');
    }

    /// <summary>
    /// 常量时间口令比对。
    /// 先把两边都哈希到等长再比较：这样"长度不同"也不会泄露长度信息，
    /// 且比较耗时与内容无关（FixedTimeEquals 不提前返回）。
    /// </summary>
    public bool VerifyPassword(string? candidate)
    {
        if (string.IsNullOrEmpty(candidate))
        {
            return false;
        }

        // 规范化候选口令：终端 cat 口令文件、剪贴板、输入法都可能带出不可见字符 ——
        // UTF-8 BOM(U+FEFF)、零宽空格(U+200B)、首尾空白。它们肉眼不可见，
        // 却会让哈希比对必然失败，用户看到的现象就是「口令明明抄对了却提示错误」。
        // 注意 string.Trim() 不剥离 U+FEFF（它不是空白字符），所以必须显式处理。
        candidate = candidate.Trim().Trim('\uFEFF', '\u200B').Trim();
        if (candidate.Length == 0)
        {
            return false;
        }

        var candidateHash = SHA256.HashData(Encoding.UTF8.GetBytes(candidate));
        var expectedHash = SHA256.HashData(_passwordBytes);
        return CryptographicOperations.FixedTimeEquals(candidateHash, expectedHash);
    }

    /// <summary>签发一个新会话，返回会话标识（写进 Cookie）。</summary>
    public string CreateSession()
    {
        var sid = Convert.ToBase64String(RandomNumberGenerator.GetBytes(32))
            .Replace('+', '-')
            .Replace('/', '_')
            .TrimEnd('=');

        _sessions[sid] = new SessionEntry
        {
            ExpiresAtUnix = DateTimeOffset.UtcNow.ToUnixTimeSeconds() + (long)SessionTtl.TotalSeconds
        };

        PruneExpired();
        return sid;
    }

    /// <summary>
    /// 校验会话；有效则**滑动续期**（一直在用就不会中途被踢）。
    /// 每次调用顺手清一次过期项，避免字典无限增长。
    /// </summary>
    public bool IsValid(string? sid)
    {
        if (string.IsNullOrWhiteSpace(sid) || !_sessions.TryGetValue(sid, out var entry))
        {
            return false;
        }

        var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        if (entry.ExpiresAtUnix <= now)
        {
            _sessions.TryRemove(sid, out _);
            return false;
        }

        entry.ExpiresAtUnix = now + (long)SessionTtl.TotalSeconds;
        return true;
    }

    public void Revoke(string? sid)
    {
        if (!string.IsNullOrWhiteSpace(sid))
        {
            _sessions.TryRemove(sid, out _);
        }
    }

    /// <summary>这个来源是不是已经被失败次数打满（超过就暂时别让它再试）。</summary>
    public bool IsRateLimited(string clientKey)
    {
        if (!_failures.TryGetValue(clientKey, out var entry))
        {
            return false;
        }

        var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        if (now - entry.WindowStartUnix > (long)FailureWindow.TotalSeconds)
        {
            _failures.TryRemove(clientKey, out _);
            return false;
        }

        return entry.Count >= MaxFailuresPerWindow;
    }

    /// <summary>记一次失败。返回当前窗口内的累计次数（供日志用）。</summary>
    public int RecordFailure(string clientKey)
    {
        var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        var entry = _failures.AddOrUpdate(
            clientKey,
            _ => new FailureEntry { Count = 1, WindowStartUnix = now },
            (_, existing) =>
            {
                if (now - existing.WindowStartUnix > (long)FailureWindow.TotalSeconds)
                {
                    existing.Count = 1;
                    existing.WindowStartUnix = now;
                }
                else
                {
                    existing.Count++;
                }
                return existing;
            });

        return entry.Count;
    }

    /// <summary>登录成功 → 清掉这个来源的失败计数。</summary>
    public void ClearFailures(string clientKey) => _failures.TryRemove(clientKey, out _);

    private void PruneExpired()
    {
        var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        foreach (var pair in _sessions)
        {
            if (pair.Value.ExpiresAtUnix <= now)
            {
                _sessions.TryRemove(pair.Key, out _);
            }
        }
    }
}