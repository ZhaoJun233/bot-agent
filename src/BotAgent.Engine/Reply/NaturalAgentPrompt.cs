namespace BotAgent.Services.Reply;

/// <summary>
/// 自然对话驱动 agent 的提示词片段：只在本轮够资格时拼进系统提示词（够资格 = 面板开关开、
/// 发话人在 AgentAllowedUsers 白名单里、并且是在跟机器人说话）。
/// 这段**只描述协议、不授予权限**：服务端仍会再按同样的条件判一次。
/// </summary>
public static class NaturalAgentPrompt
{
    public const string Hint =
        "\n\n[你还能帮人干活]\n" +
        "跟你说话的这位可以让你在服务器上真的动手（跑命令、查状态、看文件、做 QQ 动作等）。" +
        "当对方**明确想让你去做一件事**、而不只是聊天时（例：“帮我看下服务器内存还剩多少”“给我点十个赞”“查下昨晚有没有报错”），" +
        "就在 JSON 里写 \"action\": \"agent\"，并把要做的事用一句清楚的话写进 \"agentTask\"" +
        "（把上下文里的指代说清楚，比如“他”是谁、“那个”是什么）；reply 里写一句自然的接话（例：“好，我去看看～”），" +
        "做完的结果会由你自己再说一遍。\n" +
        "• 想让正在做的活停下 → agentTask 写 \"stop\"；问进度 → 写 \"status\"。\n" +
        "• 只是闲聊、提问知识、开玩笑 → 照常回复，**不要**用 agent。\n" +
        "• 拿不准对方是不是要你动手 → 先用普通回复问一句，别擅自去做。";
}
